const reverseDictionaries = Object.fromEntries(
  Object.entries(dictionaries).map(([lang, dict]) => [lang, Object.fromEntries(Object.entries(dict).map(([zh, value]) => [value, zh]))])
)

function translateText(value) {
  const trimmed = value.trim()
  if (!trimmed) return value
  const currentDict = dictionaries[locale.value] || {}
  const translated = currentDict[trimmed]
  if (translated) return value.replace(trimmed, translated)

  for (const reverse of Object.values(reverseDictionaries)) {
    const original = reverse[trimmed]
    if (original) {
      return value.replace(trimmed, currentDict[original] || original)
    }
  }
  return value
}

export function t(key) {
  if (!key) return ''
  return (dictionaries[locale.value] || {})[key] || key
}

export function setLocale(value) {
  locale.value = value
  localStorage.setItem('neop-locale', locale.value)
}

export function toggleLocale() {
  const next = locale.value === 'zh' ? 'en' : locale.value === 'en' ? 'am' : 'zh'
  setLocale(next)
}

export function applyRuntimeTranslations(root = document.body) {
  if (!root) return
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      const parent = node.parentElement
      if (!parent || ['SCRIPT', 'STYLE', 'TEXTAREA'].includes(parent.tagName)) return NodeFilter.FILTER_REJECT
      if (!node.nodeValue.trim()) return NodeFilter.FILTER_REJECT
      return NodeFilter.FILTER_ACCEPT
    }
  })
  const nodes = []
  while (walker.nextNode()) nodes.push(walker.currentNode)
  nodes.forEach((node) => {
    node.nodeValue = translateText(node.nodeValue)
  })

  root.querySelectorAll?.('[placeholder], [title]').forEach((element) => {
    if (element.hasAttribute('placeholder')) {
      element.setAttribute('placeholder', translateText(element.getAttribute('placeholder')))
    }
    if (element.hasAttribute('title')) {
      element.setAttribute('title', translateText(element.getAttribute('title')))
    }
  })
}

export function observeRuntimeTranslations(root = document.body) {
  if (!root || typeof MutationObserver === 'undefined') return undefined
  const observer = new MutationObserver(() => {
    window.requestAnimationFrame(() => applyRuntimeTranslations(root))
  })
  observer.observe(root, {
    childList: true,
    subtree: true
  })
  return observer
}
